# 이번에는 버블 정렬(Bubble Sort)이다!!
# 동작 방식 
# - 인접원소비교 : 배열의 첫번째 원소부터 시작하여 바로 옆의 원소와 값을 비교한다
# - 자리교환(swap) : 순서가 잘못되어 있다면(ex 오름차순인데 앞의 값이 뒤의 값보다 크다면) 두 원소의 위치를 서로 바꾼다.
# - 1회전 완료 : 이 과정을 끝까지 반목하면, 가장 큰 원소(오름차순 기준)가 배열의 맨 마지막 자리로 이동한다.
# - 범위 축소 : 맨 마지막으로 이동한 원소는 정렬이 완료된 것으로 간주하고 다음 회전에서는 제외한다. 전체 원소 수만큼 회전을 반복한다.

# 이웃한 요소와 비교!!
