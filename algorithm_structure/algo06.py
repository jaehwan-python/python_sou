# 함수로 알아보자
def bubble_sort(a):
    n = len(a)
    while True:
        change = False # flag(자료 앞뒤 변경 여부)

        for i in range(0, n-1):
            if a[i] > a[i+1]:
                print(a)
                a[i], a[i+1] = a[i+1], a[i]
                change = True # : 앞 뒤 값의 교환이 발생하였다

        if change == False:
            return

d = [2, 4, 5, 1, 3]
bubble_sort(d)
print()
print(d)
