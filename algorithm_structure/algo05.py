# 이번시간에는 "퀵 정렬"에 대해서 알아보자.
# 1. 피벗(pivot) 선택 : 배열 안에서 하나의 원소(기준점)를 고른다
#    ex) 첫 번째, 마지막, 중앙값, 또는 랜덤값
# 2. 분할(Partition) : 피벗을 기준으로 작은 값은 왼쪽으로, 큰 값은 오른쪽으로 재배치한다.
# 3. 재귀(Recursion) : 피벗으로 인해 나눠진 왼쪽 부분 배열과 오른쪽 부분 배열에 대해 동일하다. 
# 4. 종료 : 부분 배열의 크기가 0이나 1이 되면 정렬이 완료된다.

# 하나의 기준점을 중시믕로 작은값과 큰 값을 나눠서 각각 정렬 후 마지마겡 이어 붙이는 방법
# 'g1(기준값보다 작은 그룹)' + '기준값' + 'g2(기준값 보다 큰 그룹)'

# "피벗을 정하는 것이 가장 중요하다!"
# "Merge는 중간값으로정했다. 하지만 이번의 퀵 정렬은 피벗을 정해준다"

# <방법1> : 이해위주-quick_sort(a)
def quick_sort(a):
    n = len(a)
    if n <= 1:
        return a

    # 기준값(pivot) : 편의상 가장 마지막 값을 취한다. ... d의 가장 마지막 값은 '5'이다.
    pivot = a[-1]

    # 두 그룹을 pivot 기준으로 나누기
    g1 = [] # ... pivot보다 작은 그룹
    g2 = [] # ... pivot보다 큰 그룹

    for i in range(0, n-1):
        if a[i] < pivot:
            g1.append(a[i])
        else:
            g2.append(a[i])

    # 정렬하기
    print(f"g1({id(g1)}) : {g1}")
    print(f"g1({id(g2)}) : {g2}")
    print()
    return quick_sort(g1) + [pivot] + quick_sort(g2) # Python에서 함수는 기억장치의 새로운 공간을 차지한다. 이미 쓴 같은 기억장치를 사용하지 않고 계속 새로운 공간을 차지한다. 하지만 깊은 연산에는 좋지않다.
d = [6,8,3,1,2,4,7,5]
print(quick_sort(d))
# 한 번의 반복문을 거칠 때마다 남은 맨 마지막 값을 pivot을 잡아서 g1, g2를 구분한다.
print("-------------------------------------")

# <방법2> : 일반적인 알고리즘-quick_sort2(a)(merge)
def quick_sort2_sub(a, start, end): # start부터 end까지 '퀵 정렬'을 한다.
    # 종료조건 : 정렬 대상이 한 개 이하라면 정렬하지 않는다.
    if end - start <=0:
        return # ... 이게 재귀의 조건이다.

    # 피벗 설정
    pivot = a[end]
    i = start
    for j in range(start, end):
        if a[j] <= pivot:
            a[i], a[j] = a[j], a[i]
            print(f"{a[i]}, {a[j]} = {a[j]}, {a[i]}")
            i += 1

    a[i], a[end] = a[end], a[i]
    print(f"{a[i]}, {a[end]}, {a[end]}, {a[i]}")

    quick_sort2_sub(a, start, i - 1) # 기준값(pivot)보다 작은 그룹을 재귀로 다시 정렬
    quick_sort2_sub(a, i + 1, end) # 기준값(pivot)보다 큰 그룹을 재귀로 다시 정렬

def quick_sort2(a):
    quick_sort2_sub(a, 0, len(a) -1) # 자료, 시작index, 끝index ... 마지막 녀석은 pivot이기 때문에 제외시킴

d = [6,8,3,1,2,4,7,5]
quick_sort2(d)
