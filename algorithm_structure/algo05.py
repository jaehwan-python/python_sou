# • 버블 정렬 (Bubble Sort): 인접한 두 원소를 비교하여 자리를 계속 교환하는 방식.
# • 선택 정렬 (Selection Sort): 전체 데이터 중 가장 작은(또는 큰) 원소를 찾아 맨 앞과 교환하는 방식.
# • 삽입 정렬 (Insertion Sort): 앞에서부터 차례대로 이미 정렬된 부분과 비교하여 자신의 위치를 찾아 삽입하는 방식.

