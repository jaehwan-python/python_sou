# 실습1) 1부터 n까지 연속한 숫자의 합을 구하는 알고리즘
print('1부터 n까지 연속한 숫자의 합을 구하는 알고리즘')
print('1. 단순 계산으로 n까지의 합')
def sum_n(n):
    s=0
    for i in range(1, n+1):
        s=s+i
    return s
print(sum_n(10)) # 숫자 10까지의 합
print(sum_n(100)) # 숫자 100까지의 합
# 빅오표기법 : o(n)
# 처음 알고리즘을 공부할 때, 디버깅을 사용하면 어디 부분이 틀렸는지 알 수 있기 때문에 꼭 해보자.

print('\n 2. 가우스의 합 공식으로 n까지의 합')
def sum_2(n):
    return n * (n+1) // 2

print(sum_2(10))
print(sum_2(100))
# 빅오표기법 : o(1)


# 실습2) 최댓값구하기
print('\n최댓값 구하기')
def find_max(a):
    n = len(a)
    max_v = a[0]
    for i in range(1, n): # 0번째부터 n번째까지
        if a[i] > max_v:
            max_v = a[i] # 최댓값을 변경
    return max_v

d=[17, 92, 33, 58, 7, 32, 42]
print(find_max(d))
