# 1. **시간 복잡도** : 문제 해결하는데 걸리는 시간  -->  "빅오 표기법" : 실행속도가 빠른 순서부터 느린 순서대로 정리한다.
# 빅오(Big-O)는 입력 크기 'N'이 커질 때 '연산 횟수'가 증가하는 정도를 나타낸다.
# 실제 실행 시간(초)이 아니라 증가 추세를 비교하며, 상수 배수와 낮은 차수는 생략한다.

# 주요 단계 (N이 충분히 클 때 증가 속도가 느린 순서)
# O(1)       : 상수 시간. 데이터 크기와 무관하게 일정한 연산.        예: 배열 인덱스 접근
# O(log N)   : 로그 시간. 처리할 때마다 탐색 범위가 절반으로 줄어듦. 예: 이진 탐색
# O(N)       : 선형 시간. 데이터 개수에 비례.                       예: 전체 데이터를 한 번 순회, 순차 탐색
# O(N log N) : 선형 로그 시간.                                     예: 병합 정렬, 퀵 정렬의 평균 시간 복잡도
#              병합 정렬은 약 log N개의 단계에서 단계마다 전체 O(N)만큼 처리한다.
# O(N^2)     : 이차 시간.                                          예: 각각 N번 도는 이중 반복문, 버블 정렬, 선택 정렬
#              퀵 정렬도 최악의 경우에는 O(N^2)이다.
# O(2^N)     : 지수 시간.                                          예: N개 원소의 선택/미선택으로 모든 부분집합을 탐색하는 재귀
#              단순 재귀 피보나치도 지수적으로 증가하며 O(2^N)을 상한으로 쓸 수 있다.
#              모든 부분집합을 복사하거나 출력하면 O(N * 2^N)이 걸릴 수 있다.

# N=100일 때 증가 함수의 값 비교 (log의 밑은 2로 가정)
# O(1)       -> 1
# O(log N)   -> 약 7
# O(N)       -> 100
# O(N log N) -> 약 664 (대략 700)
# O(N^2)     -> 10,000
# O(2^N)     -> 약 1.27 * 10^30 (일반적인 환경에서는 현실적으로 처리하기 어려움)
# 위 숫자는 증가 추세를 비교하기 위한 값이며 실제 연산 횟수를 보장하지 않는다.

# 코드의 시간 복잡도를 직접 계산하는 방법
# [1단계] 입력 크기 N을 정한다. 예: 리스트 길이, 반복문의 종료값
# [2단계] 주요 연산이 몇 번 실행되는지 센다.
#         for i in range(N): -> 본문이 O(1)이면 전체 O(N)
#         N번 반복하는 안쪽 반복문을 바깥에서 N번 실행 -> O(N * N) = O(N^2)
#         탐색 범위를 매번 절반으로 줄임 -> O(log N)
# [3단계] 연속된 작업은 더한다. N번 반복 후 다시 N번 반복 -> O(2N) = O(N)
# [4단계] 상수 배수와 낮은 차수를 생략한다. 3N^2 + 2N + 5 -> O(N^2)
# [5단계]. 조건문은 실행 경로에 따라 달라지므로, 보통 최악의 경우를 기준으로 계산한다.
