# 실습3) 최대공약수구하기 : 두 수를 모두 나눌 수 있는 수 중 가장 큰 수
print('\n최대공약수 구하기')
# ex) 4, 6 : 4와 6의 공통 약수2 
# ... 우선 recursive function에 대해서 복습해보자!!

# 1. 재귀함수를 사용하지 않은 경우
def gcdFunc(a, b):
    imsi = min(a, b)
    while True:
        if a % imsi == 0  and b % imsi == 0:
            return imsi
        imsi = imsi  - 1
print(gcdFunc(4, 6))
print(gcdFunc(24, 16))
print(gcdFunc(81, 27))

# * 유클리드 호제법(Euclidean Algorithm) : 두 수의 최대공약수(GCD)를 구하기 위한 가장 오래되고 효율적인 알고리즘
# 두 수에 대해서 큰 수를 뒤에 두고 큰 수를 작은 수로 나눈 나머지에 대해서 최대 공약수를 계속 구한다.
# 두 수를 일일이 나누어 확인하는 방법(O(N))보다 훨씬 빠르게 최대공약수를 구할 수 있다.

# 2. 재귀함수를 사용한 경우(유클리드 알고리즘)
def gcdFunc2(a, b):
    if b == 0:
        return a 
    return gcdFunc2(b, a % b) # 지금 좀 더 작은 값으로 재귀호출을 하고 있다. ... 재귀호출 : 자기가 자기 자신을 호출하는 함수!
print(gcdFunc2(4, 6))
print(gcdFunc2(24, 16))
print(gcdFunc2(81, 27))
# 그냥 단순 나열한 코드(gcdFunc)보다 유클리드 알고리즘을 사용한 코드(gcdFunc2)가 더 빨리 계산된다

# 재귀함수는 호출할 때마다 계속 새로운 메모리 공간을 확보한다. 그리고 return할 때마다 다시 원래 메모리공간으로 올라가서 계산하는 형식이다!!
