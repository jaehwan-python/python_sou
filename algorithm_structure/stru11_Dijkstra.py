# Dijkstra(다익스트라) 알고리즘 : 가중치 그래프에서 한 시작 노드로부터 다른 모든 노드까지의 최단 경로를 찾는 단일 출발 최단 경로 알고리즘이다.
# 간선의 가중치가 음이 아닌 경우(0 이상)에만 사용가능하다

# 핵심원리
# 1. 탐욕적 선택 + 동적 계획법 : 매 단계에서 아직 방문하지 않은 노드 중 현재까지 아렬진 최단 거리가 가장 짧은 노들르 선택해 확정한다.(그리디+우선순위Q-알고리즘 : 매 순간 미래의 결과나 전체 상황을 따지지 않고 지금 당장 가장 좋아보이는(국소적으로 최적인) 선택을 하는 것)
# 2. 간선 완화 : 선택된 노드를 거쳐 인접 노드로 가는 비용이 기존 기록된 거리보다 작으면 최단 거리 테이블을 갱신한다.
# 3. 음수 가중치 불가 : 간선 가중치가 음수이면 이후에 더 짧은 경로가 등자하여 이미 확정된 최단 거리가 깨질 수 있으므로 벨만-포드알고리즘을 써야한다.
# BFS > DFS

# 동작과정
# 1. 시작 노드의 거리를 0, 나머지 노드의 거리를 무한대로 초기화한다.
# 2. 미방문 노드 중 최단 거리가 가장 작은 노드를 선택하고 방문 처리한다.
# 3. 선택한 노드와 연결된 인접 노드에 대해 (현재 노드 거리 + 간선 가중치)를 계산한다.
# 4. 계산값이 기존 인접 노드 거리보다 작으면 더 작은 값으로 갱신한다.
# 5. 모든 노드를 방문할 때까지 2 ~ 4번을 반복한다.

# 노드를 거치는 것이 중요한게 아니라 얼마나 가중치를 적게 받느냐가 중요한 것이댜.

