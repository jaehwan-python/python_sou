# 자료배열의 모든 요소를 앞에서부터 차례대로 이미 정렬된 부분집합과 비교하여, 자신의 위치를 

# <방법1> : 이해용 - 추가공간이 있음
def find_ins_idx(r, v):
    for i in range(0, len(r)):
        # v값이 i번 위치값보다 작으면
        if v < r[i]:
            return i
    # 적정한 위치를 못 찾은 경우 맨 뒤에 삽입
    return len(r)

def ins_sort(a):
    result = []
    while a:
        value = a.pop(0)
        ins_idx = find_ins_idx(result, value)
        result.insert(ins_idx, value)
        print('\na(=d) : ', a)
        print('result : ', result)

    return result 

d = [2, 4, 5, 1, 3]
# print(find_ins_idx(d, 4)) # 연습용
print(ins_sort(d))


# <방법2> : 일반적 - 추가 공간이 거의 없음
def ins_sort2(a):
    n = len(a)
    for i in range(1, n): # 두번째값(index 1)부터 끝까지 차례대로 삽입대상 선택
        key = a[i]
        j = i - 1 # j를 i바로 왼쪾 위치로 저장

        while j >= 0 and a[j] > key:
            a[j + 1] = a[j] # 삽입할 공간이 생기도록 값을 우측으로 밀기
            j -= 1 # 그 다음 왼쪽으로 이동하면서 다시 비교
        a[j + 1] = key # 찾은 삽입 위치에 key를 저장
        print(a)

d = [2,4,5,1,3]
ins_sort2(d)
print(d)

