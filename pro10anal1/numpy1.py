# numpy의 ndarray는 단순한 배열이라기 보다는 벡터/헹열 연산도 가능한 다차원 수치 데이터 구조이다.
# 다차원이라는 점에 주의하자. 2차원, 3차원...이 가능하다

# 주요 특징 :
# 1. 동일한 데이터 타입(Homogeneous)
# 2. 빠른 연산 속도
# 3. 메모리 효율성


import numpy as np

# < list의 경우 >
ss = ['tom', 'james', 'oscar', 1, True]
# list 여러 type의 자료로 구성
print(ss, ' ', type(ss)) # 결과 : ['tom', 'james', 'oscar', 1, True] <class 'list'>

# < array의 경우 >
ss2 = np.array(ss) # list type의 자료를 array 자료로 변환하는 코드 = list자료는 1차원 배열이기 때문에 형태는 같아도 list인지 array인지 구별할 수 있다.
print(ss2, ' ', type(ss2)) # 결과 : ['tom' 'james' 'oscar' '1' 'True'] <class 'numpy.ndarray'> 
# 배열로 바뀔 시 모두 동일한 문자열(str) type으로 들어간다. 모든 데이터가 문자열로 바뀌게 되어 ''가 붙는다. 그럼 항상 문자열로만 바뀔까? 그건아니다.
# type 순서 : bool(5등) -> int(4등) -> float(3등) -> complex(2등) -> str(1등) # 데이터 타입이 다르면 동일한 데이터 type으로 맞춰서 바꿔준다.
# 위 순서에 따라서 str인 문자가 없고 complex형태의 데이터가 있으면 모든 ndarray의 데이터가 complex형태로 바뀌게 된다.
# 이제부터는 ss2의 벡터 연산이 가능해졌다.

# 지금부터는 ss2라는 1차원 ndarray의 데이터들은 모두 문자열이고 해당 ndarray를 가지고 놀아보자.



