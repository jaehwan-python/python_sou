# 6-2. 서로 다른 주소
cc = np.copy(aa) # 복사본 별도 생성 .. 이건 참조하는 것이 아님 .. 서로 다른 주소를 참조
# 아예 새로운 객체가 생성되었다
# aa와 bb배열은 서로 동일한 객체를 바라보기에 수정을 하면 수정사항이 서로에게 반영되지만
# cc는 모양만 똑같은 배열을 새로 복사하여 새로운 객체를 생성한 독립 객체이다.
print(aa)
print(cc)

cc[0] = 77
print(aa) # 결과 : [99  2  3  4  5] 
print(cc) # 결과 : [77  2  3  4  5]
print(id(aa), ' ', id(cc))
# 둘 다 서로 같이 참조하게 된다.
# aa와 cc는 애시당초 두 주소값이 다르다.

