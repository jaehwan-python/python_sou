# < 2. 차원 >
print("< 2. 차원 >")
b = np.array([[1, 2, 3], [4, 5, 6]])
# 배열임을 선언할 때 np.array를 붙여준다.
# python의 중첩리스트를 배열화 = 2개의 행, 3개의 열 형태의 '배열'이 된다.

# 결과
print(b, ' ', b.shape, ' ', b.ndim, ' ', b.size) # 결과 : [[1 2 3]
#                                                          [4 5 6]]  (2, 3)   2   6  -> 2행3열 짜리 배열을 의미한다. 

