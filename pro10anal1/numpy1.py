# < 5. 인덱싱과 슬라이싱 >
print("< 5. 인덱싱과 슬라이싱 >")
aa = np.array([1, 2, 3, 4, 5]) 
# 이 자리에 list, tuple, set자료가 올 수 있다. 그러면 그때 np.array로 배열 type으로 바꿀 수 있다.
# 어차피 배열로 바뀌게 되면 무조건 배열로써 각 객체를 바라보기 때문이다.
# 하지만 dict는 안된다.

# 5-1. 인덱싱
print(aa, ' ', aa[1]) # 인덱싱은 '0'부터 시작한다.
# 현재 1행 5열짜리의 배열이다.

# 5-2. 슬라이싱
print(aa[1:4]) # a의 1번째에서부터 4번째 전(3번째 = 4미만) 인덱스값까지 출력
print(aa[1:])  # a에서 인덱스 1이상 모든 인덱스값 출력
print(aa[0:])  # a의 모든 값 출력
print(aa[0:5:1]) # a배열에서 0번째부터 5미만번째까지 1을 증가치로 인덱스값으로 출력(증가치1은 생략가능) -> [start : end : step(+/=)]
print(aa[-2:]) # 뒤에서부터 -1번째, 0번째 인덱스 값을 출력(뒤에서부터는 -1부터 시작)

print()


