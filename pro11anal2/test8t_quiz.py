# 예시문제2
# [one-sample t 검정 : 문제2]  
# 국내에서 생산된 대다수의 노트북 평균 사용 시간이 5.2 시간으로 파악되었다. 
# A회사에서 생산된 노트북 평균시간과 차이가 있는지를 검정하기 위해서 A회사 노트북 150대를 랜덤하게 선정하여 검정을 실시한다.  
# 실습 파일 : one_sample.csv
# 참고 : time에 공백을 제거할 땐 ***.time.replace("     ", ""),
#           null인 관찰값은 제거.

# [0단계] : 문제정의 
# 문제 : "국내 노트북 평균 사용시간인 5.2시간과 A회사에서 생산된 노트북 평균 사용 시간에 차이가 있는지 검정해보자"


# [1단계] : 가설 세우기 (A회사 중심)
# 귀무가설 : A회사 노트북 평균 사용시간은 5.2시간이다. (차이가 없다)
# 대립가설 : A회사 노트북 평균 사용시간은 5.2시간이 아니다. (차이가 있다.)


# [2단계] : 평균과 표준편차 구하기 
data2 = pd.read_csv("https://raw.githubusercontent.com/pykwon/python/refs/heads/master/testdata_utf8/one_sample.csv")
print(data2.head(3))

# [2.5단계] : 전처리를 해주어야 한다
print(data2.info())
data2['time'] = data2['time'].replace("    ", "").str.strip()
# 공백을 제거한다.

data2['time'] = pd.to_numeric(data2['time'], errors='coerce')
# str을 숫자로 바꿈

data2 = data2.dropna(subset=['time'])

print("표본 평균 사용시간 : ", data2['time'].mean())
# 결과 : 5.556880

print("표본 크기 : ", len(data2))
# 결과 : 109
# 30개의 결과가 넘기 때문에 굳이 정규성 확인을 할 필요가 없다.


# [3단계] : 정규성 확인
result2 = stats.shapiro(data2['time'])
print("time에 대한 shapiro result : ", result2) # 3가지 중 shapiro test를 사용함
# 결과 : time에 대한 shapiro result :  ShapiroResult(statistic=np.float64(0.9913731949455209), pvalue=np.float64(0.7242303346582368))
#       p값(0.72423) > 유의수준(0.05)
# 해석 : p값이 더 크므로 정규성을 확보하고 있다.
# 그러니 t-test로 넘어가라.
# 만약 정규성을 확보하지 않는다면 비모수 검정방법인 wilcoxon을 사용해라


# [4단계] : 정규성을 만족하니까 t-test이용
t_result2 = stats.ttest_1samp(data2['time'], popmean=5.2)
print("t_result2 : ", t_result2)
# 결과 : t_result2 :  TtestResult(statistic=np.float64(3.9460595666462424), pvalue=np.float64(0.00014166691390197136), df=np.int64(108))
#        p값(0.0001) < 유의수준(0.05) 


# [5단계] : 해석 : 대립가설을 채택한다
# 즉, A회사 노트북 평균 사용시간은 5.2시간이 아니다!


