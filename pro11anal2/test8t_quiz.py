# 예시문제3
# [one-sample t 검정 : 문제3]  

# https://www.price.go.kr/tprice/portal/main/main.do 에서 
# 메뉴 중,  가격동향 -> 개인서비스요금 -> 조회유형:지역별, 품목:미용 자료(엑셀)를 파일로 받아 미용 요금을 얻도록 하자. 
# 정부에서는 전국 평균 미용 요금이 15000원이라고 발표하였다. 이 발표가 맞는지 검정하시오. (월별)

# [0단계] : 문제정의 
# 문제 : "정부에서는 전국 평균 미용 요금이 15000원이라고 발표하였다."


# [1단계] : 가설 세우기 
# 귀무가설 : 전국 평균 미용 요금은 15000원이다.(발표가 맞다)
# 대립가설 : 전국 평균 미용 요금은 15000원이 아니다.(발표가 틀리다)
# pip install xlrd

# [2단계] : 평균과 표준편차 구하기 
data3 = pd.read_excel("개인서비스지역별_동향[2026-09월]1026-5시35분.xls")
print(data3.head(3))

# [2.5단계] : 전처리를 해주어야 한다
data4 = data3.iloc[0, 2:]
# 지역 데이터만 추출
data4 = pd.to_numeric(data4, errors='coerce')
data4 = data4.dropna()
# 결측값 제거

print("표본 평균 미용 요금 : ", data4.mean())
# 결과 : 202322
print("표본 크기 : ", len(data4))
# 결과 : 16
# 30개의 결과가 넘지 않기 때문에 굳이 정규성 확인을 한다.


# [3단계] : 정규성 확인
result3 = stats.shapiro(data4)
print("data4에 대한 shapiro result : ", result3) # 3가지 중 shapiro test를 사용함
# 결과 : ShapiroResult(statistic=0.942035115554694, pvalue=0.3746942909463131)
#       p값(0.37469) > 유의수준(0.05)
# 해석 : 정규성을 기각할 통계적 근거가 부족하다.
# 그러니 t-test로 넘어가라.
# 만약 정규성을 확보하지 않는다면 비모수 검정방법인 wilcoxon을 사용해라


# [4단계] : 정규성을 만족하니까 t-test이용
t_result3 = stats.ttest_1samp(data4, popmean=15000)
print(t_result3)
# 결과 : TtestResult(statistic=np.float64(7.496645276690416), pvalue=np.float64(1.8990407726371975e-06), df=np.int64(15))
#        p값(1.89904) > 유의수준(0.05) 

# [5단계] : 해석 : 귀무가설을 유지한다
# 즉, 전국 평균 미용 요금은 15000원이 아니다.(발표가 틀리다)