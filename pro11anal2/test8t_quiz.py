# 예시문제1
# [one-sample t 검정 : 문제1]  

# 영사기( 프로젝터 )에 사용되는 구형 백열전구의 수명은 250 시간이라고 알려졌다. 

# 한국 연구소에서 수명이 50 시간 더 긴 새로운 백열전구를 개발하였다고 발표하였다. = 300시간
# 연구소의 발표결과가 맞는지 새로 개발된 백열전구를 임의로 수집하여 수명 시간 관련 자료를 얻었다. 
# 한국 연구소의 발표가 맞는지 새로운 백열전구의 수명을 분석하라.

# 수집된 자료 :  305 280 296 313 287 240 259 266 318 280 325 295 315 278


# [0단계] : 문제정의
# 문제 : "새로 개발된 백열전구의 수명은 300시간인지 검정해보자"


# [1단계] : 가설 세우기
# 귀무가설 : 한국 연구소에서 개발한 백열전구의 '평균' 수명은 300시간이다.
# 대립가설 : 한국 연구소에서 개발한 백열전구의 '평균' 수명은 300시간이 아니다.


# [2단계] : 평균과 표준편차 구하기
import pandas as pd
import numpy as np
import scipy.stats as stats

data = [305, 280, 296, 313, 287, 240, 259, 266, 318, 280, 325, 295, 315, 278]
print("표본 '평균' 수명 : ", np.mean(data))
# 결과 : 289.7857

print("표본 크기 : ", len(data))
# 결과 : 14
# 표본의 갯수가 30개 이하이므로 정규성 확인을 한다!


# [3단계] : 정규성 확인
result = stats.shapiro(data)
print("shapiro result : ", result) # 3가지 중 shapiro test를 사용함
# 결과 : shapiro result :  ShapiroResult(statistic=np.float64(0.9661143911046914), pvalue=np.float64(0.8208613455706646))
#        p값(0.82085) > 유의수준(0.05)
# 해석 : p값이 더 크므로 정규성을 확보하고 있다.


# [4단계] : 정규성을 만족하니까 t-test이용
t_result = stats.ttest_1samp(data, popmean = 300)
print("t_result : ", t_result)
# 결과 : t_result :  TtestResult(statistic=np.float64(-1.556435658177089), pvalue=np.float64(0.143606254517609), df=np.int64(13))
#        p값(0.1436) > 유의수준(0.05) 


# [5단계] : 해석 : 귀무가설을 채택한다
# 즉, 한국 연구소에서 개발한 백열전구의 평균수명은 300시간이다.

