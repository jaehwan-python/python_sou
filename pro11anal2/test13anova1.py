# [3단계] : anova를 위한 lin_model불러오기
print("ANOVA검정")

import statsmodels.api as sm
# anova를 위해서는 f값이 필요하다.
# 그래서 f값을 얻기 위해 회귀분석 모델을 사용한다!

# 중요(수식코드)...회귀분석모델을 불러와!!
lin_model = ols("data['score'] ~ data['method']", data=data).fit() 
# = 회귀분석 모델 객체를 생성

result = sm.stats.anova_lm(lin_model, typ=1)
# anova_lm이라는 라이브러리는 회귀분석모델을 필요로 하기 때문에 우리가 직접
# 회귀분석모델을 만들어주었다.
pd.set_option('display.max_columns', None)
print(result)
# 결과 : 
#                      df(자유도)    sum_sq(제곱합)    mean_sq(제곱평균)        F값        PR(>F)(p값)
#    data['method']          1.0         27.980888       27.980888(MSR)    0.122228          0.727597
#    Residual(잔차)         76.0      17398.134497       228.922822(MSE)        NaN               NaN

# [4단계] : t값과 f값을 통한 가설 검증
# DataFrame해석 -> 
# 제곱평균에서 27.980888(MSR) / 228.922822(MSE) 를 해주면 F값인 0.122228이 나온다.
# F검정통계량 : 0.122228
# p-value    : 0. 0.727597
# 해석 : p-value(0. 0.727597) > alpha(0.05)이므로 귀무가설을 채택한다.
#       즉, 3가지 교육방법에 따른 실기시험 평균 점수에 차이가 없다!!

f_value = result.loc["data['method']", "F"]
p_value = result.loc["data['method']", "PR(>F)"]
print("f_value : ", f_value)
# 결과 : f_value :  0.1222284760031028

print("p_value : ", p_value)
# 결과 : p_value :  0.7275969113136878

# 교육방법별 평균 점수 ... 이제 평균구하기...ㄷㄷㄷ
print("\n 교육방법별 평균 점수 : , \n")
print(data.groupby('method')['score'].mean())
# 결과 : 
#   method
#     1      67.384615
#     2      68.357143
#     3      68.875000

# 하지만 anova는 평균의 차이가 없다라고 뭉뚱그려서 말한다.
# 우리는 상세하게 그 차이의 값을 알 수 없다.
# ANOVA는 각 '교육방법'은 1:! 평균비교는 알려주지 않는다.
# ...그래서 등장한 것이 '사후분석'이다. 사후 분석을 사용하면 어느 그룹과의 평균값이 의미가 있는지 없는지를 알 수 있따.
from statsmodels.stats.multicomp import pairwise_tukeyhsd
tukResult = pairwise_tukeyhsd(endog = data['score'], groups=data['method'])
print(tukResult)
# ====================================================
# group1 group2 meandiff p-adj   lower   upper  reject
# ----------------------------------------------------
#      1      2   0.9725 0.9702 -8.9458 10.8909  False
#      1      3   1.4904 0.9363 -8.8183  11.799  False
#      2      3   0.5179 0.9918 -9.6125 10.6483  False
# ----------------------------------------------------

# tukeyhsd 시각화
import matplotlib.pyplot as plt
tukResult.plot_simultaneous(xlabel='mean', ylabel='group')
plt.show()
# Turkey HSD : 원래 반복 수가 동일하다는 가정하에 고안된 방법
# 집단 간 평균 차이를 정밀하게 확인 가능
# 각 집단의 표본 수의 차이가 크면 결과의 신뢰가 떨어짐.
# 그래서 집단 내 표본의 분산(차이)은 좁게, 집단 간 표본의 분산(차이)은 크게 잡아야 한다.