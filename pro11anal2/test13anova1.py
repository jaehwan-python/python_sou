# 50%    40.500000   2.000000   1.000000   65.000000
# 75%    60.500000   3.000000   1.000000   78.000000
# max    80.000000   3.000000   1.000000  100.000000

# 교육 방법별 만족 건수 - 교차표(crosstab) 사용
ctab = pd.crosstab(data['method'], data['survey'])
ctab.index = ['교육방법1', '교육방법2', '교육방법3']
ctab.columns = ['만족', '불만족']
print(ctab)
#            만족  불만족
# 교육방법1    9      17
# 교육방법2   10      18
# 교육방법3    8      16
