# 분산분석 (ANalysis Of Variance)
# : 3개 이상의 모집단에 대한 가설검정
# : 분산이 발생한 과정을 분석하여 요인에 의한 분산과 요인을 통해 나누어진 각 집단 내의 분산으로 나누고 요인에 의한 분산이 의미 있는 크기를 가지는지를 검정하는 것을 의미한다.
# 3개 집단 이상의 평균비교에서는 독립인 두 집단의 평균 비교를 반복하여 실시할 경우에 제 1종오류가 증가하게 되어 문제가 발생한다. = t검정을 여러번 하는 것
# 이를 해결하기 위해 Fisher가 개발한 분산분석을 이용하게 된다.
# 분산이 발생한 과정을 분석하여 요인에 의한 분산과 요인을 통해 나눠진 각 집단 내의 분산으로 나누고, 요인에 의한 분산이 의미있는 크기를 가지는지를 검정한다.

# 요인 내에 그룹이 몇개인지를 알아야 한다. 

# f값 = 집단간분석 / 집단내분산

# 카이제곱과 유사한 그래프에서 임계값을 기준으로 f값이 기각역에 있냐 채택역에 있냐의 차이로 가설을 검정한다

# 집단 간 분산(Between Variance)이 커진다 = f값이 커지면 p값이 작아진다 = 대립가설을 채택한다.
# 그룹 내 분산은 모여있어야 좋고 그룹 간 분산은 퍼져 있어야 좋다.

# 종류 
# 1. 일원분산분석(ONE-WAY ANOVA) : 종속변수(영향변수)를 집단으로 나눠 가능한 많은 분산을 설명하는 것이 목적이다.
#                                 3개 이상의 독립적인 각 집단의 평균이 통계적으로 의미가 있는 정도로 
#                                 차이가 있는지를 결정하는데 사용된다. 
#                                 이 때 귀무가설은 '모든 개별 집단의 평균값과 같다'가 된다.

# 2. 이원분산분석(TWO-WAY ANOVA)

# 3. 사후분석(사후검정)

