# 실습) 3가지 교육방법을 적용하여 1개월 동안 교육받은 교육생 80명을 대상으로 실기시험을 실시. 
# three_sample.csv

# [1단계] : 가설 설정
# 독립변수(범주형) : 요인(교육방법)은 하나이다 - 교육방법의 종류가 3가지이다. = 그룹이 3개이다 = t-test를 사용하지 않는다.
# 종속변수(연속형) : 실기시험의 평균점수

# 귀무가설(영 가설)  : 3가지 교육방법에 따른 실기시험의 평균점수의 차이가 없다.
# 대립가설(연구가설) : 3가지 교육방법에 따른 실기시험의 평균점수의 차이가 있다.

# [2단계] : 평균 구하기(+ 이상치 구하기)
import pandas as pd
import scipy.stats as stats
from statsmodels.formula.api import ols
# 추정 및 검정, 회귀, 시계열 분석 등의 기능을 제공한다.
# ols(Ordinary Least Squares - 최소 제곱법 회귀를 이용하여 a와b값을 얻어낸다.)

data = pd.read_csv("https://raw.githubusercontent.com/pykwon/python/refs/heads/master/testdata_utf8/three_sample.csv")
# 외부 데이터 불러오기
print(data.head(3), ' ', len(data))
print(data.describe())
# 결과 : 
#             no     method     survey       score
# count  80.0000  80.000000  80.000000   80.000000
# mean   40.5000   1.962500   0.650000   78.212500
# std    23.2379   0.802587   0.479979   64.886404
# min     1.0000   1.000000   0.000000   33.000000
# 25%    20.7500   1.000000   0.000000   58.000000
# 50%    40.5000   2.000000   1.000000   65.000000
# 75%    60.2500   3.000000   1.000000   79.500000
# max    80.0000   3.000000   1.000000  500.000000

# 이상치(outlier) 확인
# 방법1. 시각화
import matplotlib.pyplot as plt
plt.boxplot(data.score)
# 사분위수를 이용하여 이상치를 그래프로 확인한다. 지금 그래프를 보면 일부값이 이상치로 존재한다.
plt.show()
# 방법2. 수치화
# 이 이상치를 수치(값)로 표현하고 싶다.
# IQR로 구한다
q1 = data['score'].quantile(0.25)
q3 = data['score'].quantile(0.75)
iqr = q3 - q1

# 이상치 기준
lower = q1 - 1.5 * iqr
upper = q3 + 1.5 * iqr
print(f"Q1:{q1}, Q3:{q3}, IQR:{iqr}")
print("이상치 하한 값: ", lower)
print("이상치 상한 값: ", upper)
# 결과 : 
# Q1(0.25) : 58.0,   Q3(0.75) : 79.5,   IQR : 21.5
# 이상치 하한 값:  25.75
# 이상치 상한 값:  111.75
# 상한과 하한 바깥의 값이 "이상치"이다.
outlier = data[(data['score'] < lower) | (data['score'] > upper)]
print('outlier : ', outlier)
print('outlier의 갯수 : ', len(outlier))
# outlier :          no    method  survey   score
#            7번      8       2       1      500
#           59번     60       1       0      438
# outlier의 갯수 : 2개
# ----------------------------------------------------------------------------------------

data = data.query("score <= 100")
# 시험점수이므로 100점 이내의 값만 작업에 참여
print(len(data))
print(data.describe())
# 결과 : 
#               no     method     survey       score
# count  78.000000  78.000000  78.000000   78.000000
# mean   40.666667   1.974359   0.653846   68.192308
# std    23.137459   0.805410   0.478822   15.043709
# min     1.000000   1.000000   0.000000   33.000000
