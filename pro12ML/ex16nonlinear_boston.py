# 이렇게 degree에 의해서 변수가 더 생겼따.


# 단순회귀
# 1차 회귀 학습과 예측
model.fit(x, y)
x_fit = np.arange(x.min(), x.max(), 1)[:, np.newaxis]
# 넣을 값
y_lin_fit = model.predict(x_fit)
# 예측값

# 그래프에 표 사용
