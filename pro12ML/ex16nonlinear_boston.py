# 저소득층 인구(LSTAT)와 주택가격(MEDV)의 관계가 매우 강한 음의 상관관계이다. : -0.737663
# LSTAT가 증가할 때 MEDV는 강하게 감소하는 추세를 보인다.

x = df[['LSTAT']].values
y = df[['MEDV']].values
# 내가 지정한 독립변수와 종속변수를 모두 2차원 배열형태로 만들었따.
