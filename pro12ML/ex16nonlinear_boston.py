# 이제부터 단항을 통한 단순선형회귀모델 제작
model = LinearRegression()

# 다항 특성(변수) 설정
quad = PolynomialFeatures(degree=2)  # -> 최대 2차항까지 만든다. 
cubic = PolynomialFeatures(degree=3) # -> 최대 3차항까지 만든다.
x_quad = quad.fit_transform(x)   #  =  기존 x를 [1, x, x²]로 변환한다.
x_cubic = cubic.fit_transform(x) #  =  기존 x를 [1, x, x², x³]로 변환한다.
print(x_quad[:3])
print(x_cubic[:3])
