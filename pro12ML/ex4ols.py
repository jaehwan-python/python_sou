# 선형회귀모델 추세식 계산(최소제곱법) 클래스
class MySimpleLinearRegression:
    def __init__(self):
        self.w = None
        self.b = None

    def fit(self, x:np.ndarray, y:np.ndarray):
        x_mean = np.mean(x)
        y_mean = np.mean(y)

        # 최소제곱법 공식 적용
        # 1. 기울기(weight) 구하기
        bunja = np.sum((x - x_mean) * (y - y_mean))
        bunmo = np.sum((x - x_mean)**2)
        self.w = bunja / bunmo 
        # 이것이 weight(기울기)이다.

        # 2. 절편(bias) 구하기
        self.b = y_mean - (self.w * x_mean)
        # 이것이 bias(절편)이다.

    def predict(self, new_x:np.ndarray):
    # 추정된 weight와 bias를 이용하여 새로운 x에 대한 예측y값을 도출한다.    
        return self.w * new_x + self.b


