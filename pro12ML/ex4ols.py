# 이를 상관관계로 나타내면 굉장히 강한 상관성을 드러낸다고 할 수 있다.
# = x가 커질때 y도 커지는 구조이기때문이다.

# 우리는 저 4개의 점의 평균을 관통하는 추세선을 만들어야 한다.
# 그리고 그 추세선을 기준으로 임의의 x값에서의 y값을 유추할 수 있다.
# 즉, 경험하지 못한 독립변수에 대한 종속변수의 값을 얻을 수 있다.

# 정량적 분석 : 회귀분석 ... 우리가 하고 있는 것
# 정성적 분석 : classiication

# 주어진 데이터를 내가 행렬곱으로 할 수 있도록 재배치
A = np.vstack([x, np.ones(len(x))]).T
print(A)
# 결과 : 
#       [ [0. 1.]
#         [1. 1.]
#         [2. 1.]
#         [3. 1.] ]

# 첫번째 열은 기울기'w'를
# 두번째 열은 절편'b'를 적용하기 위한것
# [0, 1] → 0*w + 1*b
# [1, 1] → 1*w + 1*b
# [2, 1] → 2*w + 1*b
# [3, 1] → 3*w + 1*b

# y = wx+b의 w, b구하기
import numpy.linalg as lin 
weight, bias = lin.lstsq(A, y)[0] # "최소제곱법(lstsq)" 연산!!
print(weight, ' ', bias)
# 결과 : 0.96   -0.9899999999999998

# 회귀식 형태 ->  y = wx+b
# 회귀식 : 예측y = 0.96 * x - 0.99
#        -> x가 '1'증가하면 예측값 y는 0.99증가한다.

print(0.96 * 0 + -0.9899999999999998) # 실제 y값 : -1    /  예측값 : -0.9899999999999998
print(0.96 * 1 + -0.9899999999999998) # 실제 y값 : 0.2   /  예측값 : -0.029999999999999805
print(0.96 * 2 + -0.9899999999999998) # 실제 y값 : 0.5   /  예측값 : 0.9300000000000002
print(0.96 * 3 + -0.9899999999999998) # 실제 y값 : 2.1   /  예측값 : 1.8900000000000001
print(0.96 * 7 + -0.9899999999999998) # 실제 y값 : 2.1   /  예측값 : 5.73

# 손실 : 실제값과 예측값의 차이 
# 손실을 모두 더하면 거의 '0'이 나온다.
# 잔차 : 실제값과 예측값의 차이
# , y = 0.96x - 0.99는 모든 실제값을 정확하게 재현하는 식이 아니라, 
# 네 점 전체의 추세를 가장 잘 나타내는 직선

plt.scatter(x, y, marker='o', label='실제t값')
