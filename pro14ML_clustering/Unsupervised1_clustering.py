# 군집분석의 구분
# 1. 계층적 군집 : 군집을 단계적으로 합치거나 나누어 계층 구조를 만든다.
#    - 응집형(상향식) : 각 데이터를 개별 군집으로 시작하여 비슷한 군집끼리 합친다.
#                      → 연결 방법 : 최단연결법 / 최장연결법 / 중심연결법 / 평균연결법 / 와드연결법
#    - 분리형(하향식) : 모든 데이터를 하나의 군집으로 시작하여 점차 작은 군집으로 나눈다.
#
# 2. 비계층적 군집 : 계층 구조를 만들지 않고 데이터를 군집으로 묶는다.
#    - 방법 : K-means clustering / 동시 군집 분석법 / 최적할당 군집 분석법
#    - 일반적으로 응집형과 분리형으로 구분하지 않는다.


# 현재 코드의 linkage(dist_vec, method='ward')는 계층적 군집의 응집형이며,
# 군집을 합치는 기준으로 '와드연결법'을 사용한다.


# 결국 군집과 군집 간의 거리를 확인해서 한다. 왜?? -> 어떤 군집을 서로 합칠지 결정하기 위해서이다.
# <응집형 계층적 군집화>
# 1. 처음에는 데이터 하나하나를 각각 군집으로 본다.
# 2. 군집 사이의 거리를 계산한다. -> 유클리디안 거리
# 3. 가장 가까운 두 군집을 합친다.
# 4. 합쳐진 군집을 기준으로 거리를 다시 계산하며 반복한다.

# ex)
# A와 B의 거리 = 1
# A와 C의 거리 = 8
# B와 C의 거리 = 7

# → 가장 가까운 A와 B를 먼저 합침
# → 이후 {A, B} 군집과 {C} 군집의 거리를 계산

# 그런데 {A, B}에는 점이 여러 개 있으므로 군집 사이의 거리를 어떻게 정의할지 정해야 한다.
# - 최단연결법: 두 군집에서 가장 가까운 점 사이의 거리
# - 최장연결법: 두 군집에서 가장 먼 점 사이의 거리
# - 평균연결법: 두 군집에 속한 점들 사이의 모든 거리를 평균
# 즉, "정답 label"이 없으므로, '두 점 사이의 거리'로 비슷한 정도를 판단하고 '가까운 군집'부터 합치는 것입니다.


# 두 점 사이의 거리
# - 유클리디안 거리 o
# - 맨해튼 거리 

# ------------------------------------------------------------------------------
import numpy as np
import pandas as pd 
import matplotlib.pyplot as plt

np.random.seed(123)
var = ['x', 'y']
labels = ['점0', '점1', '점2', '점3', '점4'] 
# 실제 y값으로 지도학습처럼 정답에 대한 패턴을 학습하는 것이 아니라 데이터(feature)를 주어주면 ML모델이 
# 여기서 우리가 정한 거리 계산 방법이나 군집을 합치는 방법을 정해주면, 모델이 특성이 비슷한 데이터끼리 묶는 것이다.
# 이러한 클러스터링도 데이터의 패턴을 찾는 학습이다.
# 다만, 지도학습처럼 정답을 보고 배우는 대신, 데이터 자체에서 비슷한 구조를 찾는 과정이다.
# 즉, 입력값만 보고 데이터 사이의 유사성과 그룹 구조를 찾는것이다.

x = np.random.random_sample([5, 2])
df = pd.DataFrame(x, columns=var, index=labels)
print(df)
# 결과 : 
#            x         y
#   점0  0.696469  0.286139
#   점1  0.226851  0.551315
#   점2  0.719469  0.423106
#   점3  0.980764  0.684830
#   점4  0.480932  0.392118

plt.scatter(x[:,0], x[:,1], c='blue', marker='o', s=50)

# text 추가
for i, txt in enumerate(labels):
    plt.text(x[i, 0], x[i, 1], txt)

plt.grid(True)
plt.show()

# 각 점 간의 거리 계산 ... pdist함수 사용 : 데이터의 모든 서로 다른 '두 점 사이 거리'를 계산하는 함수-유클리디안 거리
from scipy.spatial.distance import pdist, squareform
dist_vec = pdist(df, metric='euclidean')
print('각 점 사이의 거리 : ', dist_vec)
# 결과 :
# 각 점 사이의 거리 :  [0.53931329  0.13888478  0.489671  0.24018263  0.50902789  0.76564396  0.29983435  0.36983006  0.24054157  0.57923464]
# 하지만 여기서 어떤 점과 어떤 점 사이의 거리가 이만큼 나오는지 자세히 알 수는 없다. + 보기도 불편하다. 그래서...

# pdist의 결과(점과 점사이의 거리)를 사각형 형식으로 보기 ... pdist가 만든 1차원 거리 배열을 정사각형 거리 행렬로 바꾸는
row_dist = pd.DataFrame(squareform(dist_vec), 
                        columns=labels,  # 열 이름: 점0~점4
                        index=labels)    # 행 이름: 점0~점4 ... 행과 열 모두 점 이름이 붙어서, 각 점 사이의 거리를 확인
print(row_dist)
# 이제 각 점들의 거리가 어떤 점과 어떤 점의 관계인지 상세히 알 수 있다.
# 결과 : 
#           점0        점1       점2       점3       점4
#    점0  0.000000  0.539313  0.138885  0.489671  0.240183
#    점1  0.539313  0.000000  0.509028  0.765644  0.299834
#    점2  0.138885  0.509028  0.000000  0.369830  0.240542
#    점3  0.489671  0.765644  0.369830  0.000000  0.579235
#    점4  0.240183  0.299834  0.240542  0.579235  0.000000
print()

# 구분 - 계층적 군집 - 최단연결법 / 최장연결법 / 중심연결법 / 평균연결법 / 와드연결법
#      - 비계층적 군집 - K-means clustering / 동시 군집 분석법 / 최적할당 군집 분석법

# 계층적 군집-와드연결법
from scipy.cluster.hierarchy import linkage
row_clusters = linkage(dist_vec, method='ward')  # 와드연결법으로 거리가 서로 가까운 점들끼리 군집을 합쳤다.
print(row_clusters)
# dist_vec에 저장된 점 사이의 거리를 이용해서, linkage()가 와드 연결법으로 점들을 차례대로 합쳐 군집화
df2 = pd.DataFrame(row_clusters, columns=['군집id1', '군집id2', '거리', '군집멤버'])
print(df2)
# 결과 : 
#      군집id1  군집id2      거리      군집멤버
#   0    0.0      2.0      0.138885     2.0개
#   1    4.0      5.0      0.265711     3.0개
#   2    1.0      6.0      0.545400     4.0개
#   3    3.0      7.0      0.664710     5.0개

#      군집id1  군집id2     거리    군집멤버
#   0    0.0      2.0    1.388848     2.0   <-- 점0.0과 점2.0를 병합, 병합된 군집의 데이터 수 : 2.0개, 새로운 군집 ID : 5.0
#   1    4.0      5.0    2.657109   3.0개   <-- 점4.0와 군집5.0를 병합, 병합된 군집의 데이터 개 : 3.0개, 새로운 군집 ID : 6.0
#   2    1.0      6.0    5.454004   4.0개   <-- 점1.0과 군집6.0을 병합, 병합된 군집의 데이터 개 : 4.0개, 새로운 군집 ID : 7.0
# 군집7.0 = {점0, 점1, 점2, 점4}
#   3    3.0      7.0    6.647102   5.0개  <--  점3.0과 군집7.0을 병합, 병합된 군집의 데이터 개 : 5.0개, 새로운 군집 ID : 8.0
# 군집8 = {점0, 점1, 점2, 점3, 점4}
# 최종적으로 5개 점이 하나의 군집이 됨.

print("\n 군집id6에 속한 멤버(점)들 보기 ---")
from scipy.cluster.hierarchy import to_tree

root, nodes = to_tree(row_clusters, rd=True) # linkage결괄를 트리구조로 변환
ids = nodes[6].pre_order()  # 군집6에 속한 원본 점id
print('군집id6의 점id : ', ids)
print('군집id6의 점 이름 : ', [labels[i] for i in ids])
print(df.iloc[ids])  # 군집id6에 포함된 실제 데이터
print()

# 군집의 계층 구조를 계통도(Dendrogram)으로 표현
from scipy.cluster.hierarchy import dendrogram
dendrogram(row_clusters, labels=labels)
plt.tight_layout()
plt.ylabel('유클리드 거리값')
plt.show()