# 1. 내장 함수 : 일부만 체험 / 파이썬에서 제공하는 기본 함수
print(sum([1,2,3])) # []의 리스트 값을 모두 더 함.
print(8, bin(8)) #십진수를 이진수를 표현함.
print(eval('4 + 5')) # 수식에 참여하고 있는 문자열(연산에 참여하고 있는)을 계산하는 함수
print(round(1.2), round(3.5), round(7.8)) # 반올림 
#이런 내장함수는 - 자주쓰는 건 그냥 쓰면 됨 - import를 굳이 안써도 된다. ... 자동으로 import까지 지원되기 때문
#               - 자주쓰지 않는 건 따로 import하여 호출할 필요가 없다.
import math
print(math.ceil(1.2), ' ', math.ceil(2.7)) # 실수를 올림
print(math.floor(1.2), ' ', math.floor(2.7)) # 실수를 내림

print()

b_list = [True, 1, False]
print(all(b_list)) # 모두 참일때만 참인 함수 # False
print(any(b_list)) # 하나라도 참이면 참인 함수 # True

data1 = [10, 20, 30]
data2 = ['a', 'b']
for i in zip(data1, data2): # 중요!! 자주 씀!! ... 두 데이터 값을 하나씩 꺼내서 쌍을 이뤄준다. 그렇게 묶인 값들은 리스트가 아닌 튜플형태다. 개수가 안맞으면 맞는것 까지만 한다. 
    print(i)

# 우리가 하는 대부분의 업무는 필요한 함수가 없는 경우가 많다. 
# 그때 우리는 우리가 직접 필요한 함수를 만들어 쓴다. = 사용자 정의 함수!!
