# import를 쓰는 경우와 안쓰는 경우
import builtins # 자동 로딩 ... import 안써도 된다.
builtins.print("안녕하세요") #... 원래는 print()도 이렇게 써야한다.

# builtins의 이름은 대표 파일명이다. = 모듈
builtins.print(sum([2,5])) # ... 원래라면 이렇게 써야한다. 하지만 builtins를 내장하고 있는 함수들이 있기에 굳이 builtins를 안써도 된다.
# 함수에 새로운 값을 넣으면 함수의 기능을 잃어버린다.
# print = 7 ... X
